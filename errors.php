<?php
require_once __DIR__ . '/includes/config.php';
require_once __DIR__ . '/includes/auth.php';
require_once __DIR__ . '/includes/db.php';

// Enforce site administrator privileges
requireAdmin();

$pageTitle = 'System & Error Logs';
$currentPage = 'errors';
require_once __DIR__ . '/includes/header.php';

$pdo = getDB();
$msg = '';
$err = '';

// 1. Clear All Errors
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'clear_all') {
    try {
        $pdo->exec("DELETE FROM error_logs");
        $msg = "All system error logs have been cleared.";
    } catch (PDOException $e) {
        $err = "Error clearing logs: " . $e->getMessage();
    }
}

// 2. Delete Single Log Entry
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'delete_entry') {
    $delId = (int)($_POST['log_id'] ?? 0);
    if ($delId > 0) {
        $stmt = $pdo->prepare("DELETE FROM error_logs WHERE id = ?");
        $stmt->execute([$delId]);
        $msg = "Log entry #{$delId} deleted.";
    }
}

// 3. Insert Test Error Entry
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'test_log') {
    logSystemError('TEST', 'Manual diagnostic test error entry generated by administrator.', "Triggered at " . date('Y-m-d H:i:s T') . "\nUser: " . ($user['full_name'] ?? 'Admin'));
    $msg = "Test diagnostic log entry successfully written.";
}

// Filters & Search
$filterType = trim($_GET['type'] ?? '');
$search = trim($_GET['search'] ?? '');

$sql = "
    SELECT e.*, u.full_name AS user_name, u.username AS user_handle
    FROM error_logs e
    LEFT JOIN users u ON e.user_id = u.id
    WHERE 1=1
";
$params = [];

if (!empty($filterType)) {
    $sql .= " AND e.error_type = :type";
    $params[':type'] = strtoupper($filterType);
}

if (!empty($search)) {
    $sql .= " AND (e.message LIKE :s OR e.details LIKE :s OR e.error_type LIKE :s)";
    $params[':s'] = "%{$search}%";
}

$sql .= " ORDER BY e.id DESC LIMIT 150";
$stmt = $pdo->prepare($sql);
$stmt->execute($params);
$logs = $stmt->fetchAll();

// Distinct types for filter dropdown
$types = $pdo->query("SELECT DISTINCT error_type FROM error_logs ORDER BY error_type ASC")->fetchAll(PDO::FETCH_COLUMN);
$totalCount = $pdo->query("SELECT COUNT(*) FROM error_logs")->fetchColumn();
?>

<?php if ($msg): ?><div class="alert alert-success"><?= htmlspecialchars($msg) ?></div><?php endif; ?>
<?php if ($err): ?><div class="alert alert-danger"><?= htmlspecialchars($err) ?></div><?php endif; ?>

<div class="card">
    <div class="card-header" style="flex-wrap: wrap; gap: 1rem;">
        <div>
            <h2 class="card-title">System &amp; Error Diagnostic Logs</h2>
            <div style="font-size: 0.85rem; color: var(--text-muted); margin-top: 2px;">
                <?= $totalCount ?> total logged events (Showing up to 150 most recent)
            </div>
        </div>

        <div style="display: flex; gap: 0.5rem; align-items: center; flex-wrap: wrap;">
            <form method="POST" action="errors.php" style="display: inline;">
                <input type="hidden" name="action" value="test_log">
                <button type="submit" class="btn btn-outline btn-sm">Write Test Entry</button>
            </form>

            <?php if (!empty($logs)): ?>
                <form method="POST" action="errors.php" onsubmit="return confirm('Permanently clear all error logs?');" style="display: inline;">
                    <input type="hidden" name="action" value="clear_all">
                    <button type="submit" class="btn btn-danger btn-sm">Clear All Logs</button>
                </form>
            <?php endif; ?>
        </div>
    </div>

    <div class="card-body">
        <!-- Filter Bar -->
        <form method="GET" action="errors.php" style="display: flex; gap: 0.75rem; margin-bottom: 1.5rem; flex-wrap: wrap; align-items: center;">
            <div style="flex: 1; min-width: 220px;">
                <input type="text" name="search" class="form-control" placeholder="Search error message, transcript, or payload..." value="<?= htmlspecialchars($search) ?>">
            </div>

            <div style="min-width: 170px;">
                <select name="type" class="form-control" onchange="this.form.submit();">
                    <option value="">All Categories</option>
                    <?php foreach ($types as $t): ?>
                        <option value="<?= htmlspecialchars($t) ?>" <?= ($filterType === $t) ? 'selected' : '' ?>>
                            <?= htmlspecialchars($t) ?>
                        </option>
                    <?php endforeach; ?>
                </select>
            </div>

            <button type="submit" class="btn btn-primary btn-sm">Filter</button>
            <?php if (!empty($search) || !empty($filterType)): ?>
                <a href="errors.php" class="btn btn-outline btn-sm">Reset</a>
            <?php endif; ?>
        </form>

        <div class="table-responsive">
            <table class="table">
                <thead>
                    <tr>
                        <th style="width: 16%;">Timestamp (Local)</th>
                        <th style="width: 12%;">Category</th>
                        <th style="width: 16%;">User / Actor</th>
                        <th style="width: 46%;">Message &amp; Diagnostic Details</th>
                        <th style="width: 10%; text-align: right;">Action</th>
                    </tr>
                </thead>
                <tbody>
                    <?php if (empty($logs)): ?>
                        <tr>
                            <td colspan="5" style="text-align: center; color: var(--text-muted); padding: 2.5rem 1rem;">
                                No system errors found. All background operations, database executions, and SMTP transactions are healthy.
                            </td>
                        </tr>
                    <?php else: foreach ($logs as $l): ?>
                        <?php
                        $badgeClass = 'badge-neutral';
                        if ($l['error_type'] === 'SMTP') $badgeClass = 'badge-danger';
                        elseif ($l['error_type'] === 'NOTIFICATION') $badgeClass = 'badge-warning';
                        elseif ($l['error_type'] === 'DATABASE') $badgeClass = 'badge-danger';
                        elseif ($l['error_type'] === 'TEST') $badgeClass = 'badge-info';
                        ?>
                        <tr>
                            <td style="font-size: 0.82rem; white-space: nowrap; vertical-align: top;">
                                <strong><?= htmlspecialchars($l['created_at']) ?></strong>
                            </td>

                            <td style="vertical-align: top;">
                                <span class="badge <?= $badgeClass ?>"><?= htmlspecialchars($l['error_type']) ?></span>
                            </td>

                            <td style="font-size: 0.85rem; vertical-align: top;">
                                <?php if (!empty($l['user_name'])): ?>
                                    <strong><?= htmlspecialchars($l['user_name']) ?></strong><br>
                                    <small style="color: var(--text-muted);">@<?= htmlspecialchars($l['user_handle']) ?> (ID: <?= $l['user_id'] ?>)</small>
                                <?php elseif (!empty($l['user_id'])): ?>
                                    <small style="color: var(--text-muted);">User #<?= $l['user_id'] ?></small>
                                <?php else: ?>
                                    <small style="color: var(--text-muted);">System / CLI Cron</small>
                                <?php endif; ?>
                            </td>

                            <td style="vertical-align: top;">
                                <div style="font-weight: 600; color: #b91c1c; font-size: 0.9rem; margin-bottom: 4px;">
                                    <?= htmlspecialchars($l['message']) ?>
                                </div>

                                <?php if (!empty($l['details'])): ?>
                                    <details style="margin-top: 0.4rem;">
                                        <summary style="font-size: 0.78rem; color: var(--primary); cursor: pointer; font-weight: 600;">
                                            View Full Transcript / Payload
                                        </summary>
                                        <pre style="background: #0f172a; color: #38bdf8; padding: 0.8rem; border-radius: 6px; font-size: 0.78rem; margin-top: 0.4rem; overflow-x: auto; white-space: pre-wrap; word-break: break-all; max-height: 240px;"><?= htmlspecialchars($l['details']) ?></pre>
                                    </details>
                                <?php endif; ?>
                            </td>

                            <td style="text-align: right; vertical-align: top;">
                                <form method="POST" action="errors.php" onsubmit="return confirm('Delete this log entry?');">
                                    <input type="hidden" name="action" value="delete_entry">
                                    <input type="hidden" name="log_id" value="<?= $l['id'] ?>">
                                    <button type="submit" class="btn btn-outline btn-sm" style="color: var(--danger); border-color: var(--border);">
                                        Delete
                                    </button>
                                </form>
                            </td>
                        </tr>
                    <?php endforeach; endif; ?>
                </tbody>
            </table>
        </div>
    </div>
</div>

<?php require_once __DIR__ . '/includes/footer.php'; ?>
